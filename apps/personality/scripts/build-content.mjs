// Turns content/**/*.md into server/content.generated.ts.
// Pages Functions cannot import .md files, so the server reads this module instead.
// Run `pnpm content` after editing anything in content/. A test fails if it is out of date.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { stdout } from 'node:process';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'content');

const paths = readdirSync(contentDir, { recursive: true, encoding: 'utf8' })
  .filter((path) => path.endsWith('.md'))
  .map((path) => path.split('\\').join('/'))
  .sort();

const entries = paths.map((path) => {
  const text = readFileSync(join(contentDir, path), 'utf8').replace(/\r\n/g, '\n');
  return `  ${JSON.stringify(path)}:\n    ${JSON.stringify(text)},`;
});

const output = [
  '// Generated by scripts/build-content.mjs from content/. Do not edit. Run `pnpm content`.',
  '// Paid text lives here, so only server/ may import this file.',
  '// prettier-ignore',
  'export const CONTENT: Record<string, string> = {',
  ...entries,
  '};',
  '',
].join('\n');

const target = join(root, 'server', 'content.generated.ts');
writeFileSync(target, output);
stdout.write(`Wrote ${relative(root, target)} from ${paths.length} files.\n`);
